export const ALL_STAGES = CHAPTERS.flatMap(c => c.stages.map(s => ({ ...s, chapterId: c.id })));

export function findStage(id) {
  return ALL_STAGES.find(s => s.id === id);
}

export function nextStageId(id) {
  const i = ALL_STAGES.findIndex(s => s.id === id);
  return i >= 0 && i < ALL_STAGES.length - 1 ? ALL_STAGES[i + 1].id : null;
}
